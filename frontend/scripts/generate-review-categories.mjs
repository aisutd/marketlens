// Regenerates src/constants/reviewCategories.js from the scorer's dev data.
//
//   npm run generate:review-categories -- [path/to/products_dev.csv]
//
// The CSV is not in git. Without a path this reads data/products_dev.csv at
// the repo root; from a worktree, pass the main checkout's copy.

import { createReadStream, writeFileSync } from "node:fs";
import process from "node:process";
import { fileURLToPath } from "node:url";

const csvPath =
  process.argv[2] ??
  fileURLToPath(new URL("../../data/products_dev.csv", import.meta.url));

const outputFile = new URL(
  "../src/constants/reviewCategories.js",
  import.meta.url
);

// Yields one array of fields per CSV row. Titles hold quoted commas, doubled
// quotes and sometimes line breaks, so splitting on lines isn't enough.
async function* readRows(path) {
  let field = "";
  let row = [];
  let quoted = false;
  let previous = "";

  for await (const chunk of createReadStream(path, { encoding: "utf8" })) {
    for (const char of chunk) {
      if (quoted) {
        if (char === '"') quoted = false;
        else field += char;
      } else if (char === '"') {
        // A quote straight after a closing quote is an escaped quote.
        if (previous === '"') field += '"';
        quoted = true;
      } else if (char === ",") {
        row.push(field);
        field = "";
      } else if (char === "\n") {
        row.push(field.endsWith("\r") ? field.slice(0, -1) : field);
        yield row;
        field = "";
        row = [];
      } else {
        field += char;
      }
      previous = char;
    }
  }

  if (field !== "" || row.length > 0) {
    row.push(field);
    yield row;
  }
}

const namesById = new Map();
let columns = null;
let total = 0;

for await (const row of readRows(csvPath)) {
  if (columns === null) {
    columns = {
      id: row.indexOf("category_id"),
      name: row.indexOf("category_name"),
      reviews: row.indexOf("reviews"),
    };
    if (Object.values(columns).includes(-1)) {
      console.error(
        `${csvPath} needs category_id, category_name and reviews columns.`
      );
      process.exit(1);
    }
    continue;
  }

  total += 1;
  if (Number(row[columns.reviews]) > 0) {
    namesById.set(Number(row[columns.id]), row[columns.name]);
  }
}

if (namesById.size === 0) {
  console.error(`No products with reviews found in ${csvPath}.`);
  process.exit(1);
}

const lines = [...namesById.entries()]
  .sort(([a], [b]) => a - b)
  .map(([id, name]) => `  ${id}, // ${name}`);

writeFileSync(
  outputFile,
  `// Generated by scripts/generate-review-categories.mjs. Don't edit by hand.
//
// Scoring categories where products_dev.csv has at least one product with
// reviews > 0. Elsewhere the scorer never saw a review count in training, so
// the frontend leaves reviews and stars out and the launch model scores it.

const REVIEW_CATEGORY_IDS = new Set([
${lines.join("\n")}
]);

export function categoryUsesReviews(categoryId) {
  return REVIEW_CATEGORY_IDS.has(Number(categoryId));
}
`
);

console.log(
  `Read ${total} products: ${namesById.size} categories have reviews.`
);
