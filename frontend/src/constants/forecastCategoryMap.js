// Returns the forecast category for a scoring category name, or null when the
// forecast doesn't cover it. hasOwn keeps names like "constructor" out.
export function toForecastCategory(scoringName) {
  return Object.hasOwn(FORECAST_CATEGORY_BY_SCORING_NAME, scoringName)
    ? FORECAST_CATEGORY_BY_SCORING_NAME[scoringName]
    : null;
}
